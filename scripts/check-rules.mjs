#!/usr/bin/env node
// check-rules.mjs
//
// Local + CI enforcement of the project rules.
// Run from the repo root:
//   node scripts/check-rules.mjs
//
// Exit codes:
//   0 = no rule violations (warnings are OK)
//   1 = at least one rule violation
//
// Each rule has a stable ID (R1, R2, ...). To allow a check on a specific file,
// add an entry to scripts/.rules-allowlist:
//
//   R9: extension/src/legacy.ts
//
// Supported glob patterns:
//   - exact path:        web/src/lib/foo.ts
//   - dir + /** suffix:  scripts/legacy/**

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, relative, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const ALLOWLIST_PATH = 'scripts/.rules-allowlist';

const EXT_TS = ['.ts', '.tsx', '.mts', '.cts'];
const EXT_SQL = ['.sql'];
const EXT_DOCS = ['.md', '.txt'];
// `.css` is scanned too: provenance notes hide in stylesheet comments just as
// easily as in code comments.
const ALL_SOURCE_EXTS = [...EXT_TS, ...EXT_SQL, '.kt', '.mjs', '.js', '.css', ...EXT_DOCS];

const BUILD_OUTPUT_DIRS = new Set([
  'dist', 'dist-firefox', 'build', '.next', '_superseded', 'coverage',
  'node_modules', '.git', '.gradle', '.kotlin', '.idea', '.cache',
]);

const SECRET_PREFIXES = [
  'AIza', 'sk-', 'sntryu_', 'sbp_', 'sb_secret_',
  'sb_publishable_', 're_', 'KGAT_',
];

// Detection signatures for provenance notes (Hard Rule 1.2). The product names
// are kept literal because the scan cannot match them otherwise - they are
// signatures, not attributions.
const PROVENANCE_PATTERNS = [
  /\bAI[\s-]?generated\b/i,
  /\bAI[\s-]?assisted\b/i,
  /\b(GPT|model)[\s-]generated\b/i,
  /\bgenerated by (an? )?(LLM|model|AI|Claude|GPT|Copilot|Cursor|Continue|Aider)\b/i,
  /\bprompted by\b/i,
  /\bthe (model|agent|LLM|AI)\b/i,
  /\bCLAUDE\.md\b/,
  /\bcopilot[\s-]?instructions\b/i,
  /\bClaude Code\b/,
  /\bChatGPT\b/,
];

// Note: the rulebook filename is intentionally not in this list. The
// rulebook lives at RULES.md and is part of RULES_FILES below.

const RULES_FILES = new Set([
  'RULES.md', 'web/RULES.md', 'extension/RULES.md',
  'supabase/RULES.md', 'android/RULES.md',
  'CONTRIBUTING.md', 'RUNBOOK.md', '.github/pull_request_template.md',
  'scripts/check-rules.mjs', 'scripts/.rules-allowlist',
  '.env.example', 'web/.env.example', 'extension/.env.example',
  'android/.env.example',
  // Public-facing contributor docs. They explicitly reference the rulebook
  // by name in places; the wording is hand-curated to comply with R2.
  'README.md', 'CODE_OF_CONDUCT.md', 'SECURITY.md', 'LICENSE',
]);

let violations = 0;
let warnings = 0;
const errors = [];
const warningsList = [];

function fail(ruleId, file, line, message) {
  violations++;
  errors.push(`  [${ruleId}] ${file}${line ? ':' + line : ''} - ${message}`);
}

function warn(ruleId, file, line, message) {
  warnings++;
  warningsList.push(`  [${ruleId}] ${file}${line ? ':' + line : ''} - ${message}`);
}

const SCRIPT_DIR = fileURLToPath(new URL('.', import.meta.url)).replace(/[\\/]+$/, '');
const CWD = process.cwd();
const ROOT = (CWD.endsWith(`${'\\'}scripts`) || CWD.endsWith('/scripts'))
  ? SCRIPT_DIR.replace(/[\\/]scripts$/, '')
  : CWD;
process.chdir(ROOT);

function loadAllowlist() {
  if (!existsSync(ALLOWLIST_PATH)) return new Map();
  const map = new Map();
  for (const raw of readFileSync(ALLOWLIST_PATH, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const idx = line.indexOf(':');
    if (idx < 0) continue;
    const ruleId = line.slice(0, idx).trim();
    const glob = line.slice(idx + 1).trim();
    if (!map.has(ruleId)) map.set(ruleId, []);
    map.get(ruleId).push(glob);
  }
  return map;
}

const ALLOWLIST = loadAllowlist();

function isAllowed(ruleId, file) {
  const entries = ALLOWLIST.get(ruleId);
  if (!entries) return false;
  const rel = file.replace(/\\/g, '/');
  return entries.some(pattern => {
    if (pattern === rel) return true;
    if (pattern.endsWith('/**')) {
      const prefix = pattern.slice(0, -3);
      return rel.startsWith(prefix + '/') || rel === prefix;
    }
    if (pattern.startsWith('**/')) return rel.endsWith(pattern.slice(3));
    return false;
  });
}

function walk(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (BUILD_OUTPUT_DIRS.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}

const allFiles = walk(process.cwd());

// Only scan files git would actually commit (tracked + untracked-but-not-ignored).
// Gitignored local-only dirs (.roam-local/, .github/skills/, internal scripts/
// seeders) are never part of the public repo, so scanning them surfaces false
// positives without protecting the public. Falls back to scanning the whole
// tree when not run inside a git repository.
function gitCommittableFiles() {
  let out;
  try {
    out = execSync('git ls-files --cached --others --exclude-standard', { encoding: 'utf8' });
  } catch {
    return null;
  }
  return new Set(out.split(/\r?\n/).filter(Boolean).map(p => p.replace(/\\/g, '/')));
}
const COMMITTABLE = gitCommittableFiles();

function isCommittable(absPath) {
  if (!COMMITTABLE) return true; // not a git repo — scan everything
  const rel = relative(ROOT, absPath).replace(/\\/g, '/');
  return COMMITTABLE.has(rel);
}

// Test files legitimately contain triggering strings (fake secrets, `as any`,
// provenance-note fixtures, empty catches) as test data. The scanner is line-based
// and cannot tell string literals from real code, so skip them — mirroring the
// Betterleaks prefilter. This keeps rule enforcement honest for shipped code.
function isTestFile(rel) {
  if (/\.(test|spec)\.[jt]sx?$/.test(rel)) return true;
  if (rel.includes('/__tests__/') || rel.includes('/_tests/')) return true;
  return false;
}

const sourceFiles = allFiles.filter(f =>
  isCommittable(f) &&
  ALL_SOURCE_EXTS.includes(extname(f)) &&
  !isTestFile(relative(ROOT, f).replace(/\\/g, '/'))
);
// Workflow files are scanned by R10 even though they aren't "source files".
const workflowFiles = allFiles.filter(f =>
  isCommittable(f) &&
  (f.endsWith('.yml') || f.endsWith('.yaml')) &&
  f.replace(/\\/g, '/').includes('.github/workflows/')
);

// ─── R1: No `[deploy]` in commit messages ──────────────────────────────────
// Matches the historical pattern used by the (now-removed) GitHub Actions
// trigger: a tag like "[deploy]" appended at the END of the subject line.
// Subject-internal "[deploy]" mentions (e.g., an explanatory commit body
// or a commit about removing the trigger) do not trip the rule.
function checkDeployTagInCommits() {
  let out = '';
  try {
    out = execSync('git log --pretty=%s origin/main..HEAD', { encoding: 'utf8' });
  } catch {
    return;
  }
  const tags = ['[deploy]', '[ship]', '[prod]', '[release]'];
  // Match: optional whitespace, the tag, optional trailing whitespace, end of line.
  const trailingTagRe = /\s*\[(deploy|ship|prod|release)\]\s*$/i;
  for (const line of out.split(/\r?\n/)) {
    if (trailingTagRe.test(line)) {
      const m = line.match(trailingTagRe);
      fail('R1', 'git log', null,
        `commit-message trigger tag "[${m[1]}]" found at end of subject - see Hard Rule 1.1`);
      return; // one violation is enough
    }
  }
}
checkDeployTagInCommits();

// ─── R11: Branch names follow <type>/<kebab> ───────────────────────────────
// Applies to the branch being pushed or opened as a pull request, never to a
// file. Editors and harnesses sometimes create branches with their own prefix;
// those names are published in PR history and break the one-concern-per-branch
// convention in Process Rule 2.1. The allowlist is deliberately positive: an
// unrecognised prefix fails rather than a blocklist of known prefixes.
// CI supplies GITHUB_HEAD_REF on pull_request and GITHUB_REF_NAME on push.
const BRANCH_ALLOWED =
  /^(feature|feat|fix|chore|docs|test|refactor|perf|audit|build|ci|release)\/[a-z0-9][a-z0-9._-]*$/;
const BRANCH_PASSTHROUGH = new Set(['', 'HEAD', 'main', 'develop']);

function currentBranchName() {
  const fromCi = process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '';
  if (fromCi) return fromCi.trim();
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function checkBranchName() {
  const name = currentBranchName();
  if (BRANCH_PASSTHROUGH.has(name)) return; // main push, detached HEAD, no repo
  if (BRANCH_ALLOWED.test(name)) return;
  fail('R11', 'git branch', null,
    `branch name "${name}" does not match <type>/<kebab> (feature|feat|fix|chore|docs|test|refactor|perf|audit|build|ci|release) - see Process Rule 2.1`);
}
checkBranchName();

// ─── R2: No provenance notes in committed files ────────────────────────────
// `supabase/migrations/_superseded/` holds historical snapshots written before
// this rule existed. They are kept for rollback documentation but excluded
// here.
function checkProvenance(file) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (RULES_FILES.has(rel)) return;
  if (rel.startsWith('supabase/migrations/_superseded/')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    for (const pattern of PROVENANCE_PATTERNS) {
      if (pattern.test(line)) {
        if (isAllowed('R2', rel)) return;
        fail('R2', rel, i + 1,
          `provenance note "${line.trim().slice(0, 80)}" - see Hard Rule 1.2`);
        return;
      }
    }
  }
}

// ─── R3: No hardcoded secrets ──────────────────────────────────────────────
function checkSecrets(file) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (rel.endsWith('.env') || rel.endsWith('.env.example') || rel.endsWith('.env.local')) return;
  if (rel.includes('.example')) return;
  if (rel.startsWith('web/coverage/') || rel.startsWith('web/.next/')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*(--|\/\/|#|<!--)/.test(line)) continue;
    for (const prefix of SECRET_PREFIXES) {
      const escaped = prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const re = new RegExp(`\\b${escaped}[A-Za-z0-9_\\-]{16,}\\b`);
      if (re.test(line)) {
        if (isAllowed('R3', rel)) return;
        fail('R3', rel, i + 1,
          `hardcoded secret prefix "${prefix}" - see Hard Rule 1.3`);
        return;
      }
    }
  }
}

// ─── R4: No .skip migrations in active directory ───────────────────────────
function checkSkipMigrations() {
  const dir = 'supabase/migrations';
  if (!existsSync(dir)) return;
  for (const f of readdirSync(dir)) {
    if (f.endsWith('.skip')) {
      fail('R4', `${dir}/${f}`, null,
        '.skip migration in active directory - move to _superseded/ per Hard Rule 1.4');
    }
  }
}
checkSkipMigrations();

// ─── R5: No duplicate component filenames ─────────────────────────────────
function checkDuplicateComponents() {
  const componentsDir = 'web/src/components';
  const appDir = 'web/src/app';
  if (!existsSync(componentsDir) || !existsSync(appDir)) return;
  const componentFiles = new Set(
    readdirSync(componentsDir, { recursive: true })
      .filter(f => extname(f) === '.tsx' || extname(f) === '.ts')
      .map(f => basename(f))
  );
  function walkApp(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) walkApp(join(dir, entry.name));
      else if ((extname(entry.name) === '.tsx' || extname(entry.name) === '.ts') &&
               componentFiles.has(entry.name)) {
        fail('R5', `${relative(ROOT, join(dir, entry.name))}`, null,
          `filename matches web/src/components/${entry.name} - duplicate-component pattern, see Hard Rule 1.7`);
      }
    }
  }
  walkApp(appDir);
}
checkDuplicateComponents();

// ─── R6: No proxy.ts in web/src/ ───────────────────────────────────────────
function checkProxyTs() {
  const candidate = 'web/src/proxy.ts';
  if (existsSync(candidate)) {
    fail('R6', candidate, null,
      'proxy.ts exists - should be middleware.ts, see Hard Rule 1.8');
  }
}
checkProxyTs();


// ─── R7: SQL migration safety (array_agg(u.*) pattern from v31) ───────────
function checkSqlPatterns(file) {
  if (!file.endsWith('.sql')) return;
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (rel.includes('_superseded')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  if (/array_agg\s*\(\s*u\./i.test(content)) {
    if (isAllowed('R7', rel)) return;
    warn('R7', rel, null,
      'migration uses "array_agg(u.*)" - verify the alias scope, see Backend Rule S.7');
  }
}

// ─── R8: No empty catch {} without comment ─────────────────────────────────
function checkEmptyCatches(file) {
  if (![...EXT_TS, '.js', '.mjs'].some(ext => file.endsWith(ext))) return;
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (rel.startsWith('node_modules/') || rel.includes('/coverage/')) return;
  let content;
  try { content = readFileSync(file, 'utf8'); } catch { /* file unreadable - skip */ return; }
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    // Skip comment-only lines and strings. Use a regex that requires the
    // catch to be at code position (not inside a `// ...` comment or string).
    if (/^\s*(\/\/|\*|<!--)/.test(line)) continue;
    // Strip line comments before testing; catches inside comments are OK.
    const code = line.replace(/\/\/.*$/, '');
    if (/catch\s*(\([^)]*\))?\s*\{\s*\}/.test(code)) {
      if (isAllowed('R8', rel)) continue;
      fail('R8', rel, i + 1, 'empty catch without comment - see Process Rule 2.5');
    }
  }
}

// ─── R9: No `as any` casts ────────────────────────────────────────────────
function checkAnyCast(file) {
  if (!EXT_TS.includes(extname(file))) return;
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (rel.startsWith('node_modules/') || rel.includes('/coverage/')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/\bas\s+any\b/.test(line)) {
      if (isAllowed('R9', rel)) continue;
      fail('R9', rel, i + 1,
        '"as any" cast - use "as unknown as T" with comment, see Process Rule 2.6');
    }
  }
}

// ─── R10: No `contains(fromJSON([...]))` predicates in workflow files ──────
// GitHub Actions' `contains()` helper does element matching on arrays, not
// glob matching. Wrapping it in `fromJSON(['supabase/functions/**'])` and
// then comparing to '**' or '*' is always false (or always true), silently
// breaking the workflow. See RULES.md §1.6½.
function checkWorkflowPathFilter(file) {
  if (!file.endsWith('.yml') && !file.endsWith('.yaml')) return;
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (!rel.startsWith('.github/workflows/')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  const lines = content.split(/\r?\n/);
  // Match an `if:` (or `steps[].if`) line that contains the antipattern.
  // We catch both the array-with-'**' form (always false) and the array-with-'*'
  // form (always true). Both hide bugs.
  const re = /contains\s*\(\s*fromJSON\s*\(/i;
  let insideIf = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*if\s*:/.test(line) || /\bif\s*:/.test(line)) insideIf = true;
    if (insideIf && re.test(line)) {
      if (isAllowed('R10', rel)) continue;
      fail('R10', rel, i + 1,
        'contains(fromJSON([...])) is always true or false in an `if:` predicate — use dorny/paths-filter instead. See RULES.md §1.6½');
    }
    if (line.trim() === '' || /^[^\s]/.test(line)) insideIf = false;
  }
}

// ─── R12: Remote Supabase commands must name --project-ref ────────────────
// `supabase db push` with no `--project-ref` targets whatever the CLI is linked
// to. Locally that link is staging (`supabase/.temp/project-ref`), which is how
// 8 migrations landed on staging on 2026-11-09 while the run was reported as
// production. The environment table lives in RUNBOOK.md.
//
// Scope is deliberately workflows only. Both deploy workflows legitimately run
// `supabase link --project-ref …` and then `db push --remote`, so a file-level
// explicit link satisfies the rule; an unlinked file must name the ref on the
// command. Docs are excluded because prose ("a migration blocks `supabase db
// push`") is indistinguishable from a command line by line, and the resulting
// noise would train everyone to ignore the check.
const SUPABASE_REMOTE_RE = /\bsupabase(?:\.exe)?\s+(?:db\s+push|db\s+reset|functions\s+(?:deploy|delete)|secrets\s+set)\b/i;

function checkRemoteSupabaseTarget(file) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (!rel.startsWith('.github/workflows/')) return;
  let content;
  try { content = readFileSync(file, "utf8"); } catch { /* file unreadable - skip */ return; }
  // An explicit link earlier in the job anchors every later command to a named ref.
  if (/supabase\s+link\s+--project-ref\b/i.test(content)) return;
  if (isAllowed('R12', rel)) return;
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!SUPABASE_REMOTE_RE.test(line)) continue;
    if (/--project-ref\b/i.test(line)) continue;
    // `db reset --local` never leaves the machine.
    if (/\bdb\s+reset\b/i.test(line) && /--local\b/i.test(line)) continue;
    fail('R12', rel, i + 1,
      'remote Supabase command without --project-ref and no `supabase link --project-ref` in this workflow - it would target the linked project (staging). See RUNBOOK.md - Environments.');
  }
}

// ─── R13: No tracked file cites a local-only tree ─────────────────────────
// `.roam-local/`, `.clinerules/`, `.github/skills/` and the five RULES.md rulebooks are never
// committed (see .git/info/exclude and .gitignore). A tracked file that cites one is a broken
// reference for every reader of the public repo - and twice it was worse than broken: three
// web/scripts read 29.78 MB of private art, so a fresh clone could not run them at all.
//
// W13 in .roam-local/scripts/check_plans.py is the plan-set view of the same rule. This one is
// the one CI can enforce, because it is tracked.
const LOCAL_TREE_RE = /(?:\.roam-local\/|\.clinerules\/|\.github\/skills\/|\bRULES\.md\b)/;

// Files whose job is to name the tree, not to depend on it. Without these the rule fails on
// untouched code, which is how a gate gets switched off.
const R13_ALLOW = new Set(['.gitignore', 'scripts/check-rules.mjs']);
// Applied migrations are immutable history, so a comment in one cannot be corrected
// retroactively. R13 cannot be retroactive there.
const R13_ALLOW_PREFIX = ['supabase/migrations/'];

const R13_EXTS = new Set([
  ...ALL_SOURCE_EXTS, '.json', '.yml', '.yaml', '.sh', '.ps1', '.psm1',
  '.html', '.toml', '.py', '.kts', '.gradle', '.xml', '.svg', '.service',
]);
// The allowlist has no extension, so it is matched by name instead: it is the one
// extensionless tracked file that sits beside the rules and can cite them.

function checkLocalTreeCitations() {
  if (!COMMITTABLE) return;
  for (const rel of [...COMMITTABLE].sort()) {
    if (R13_ALLOW.has(rel)) continue;
    if (R13_ALLOW_PREFIX.some(p => rel.startsWith(p))) continue;
    if (!R13_EXTS.has(extname(rel)) && rel !== ALLOWLIST_PATH) continue;
    let body;
    try { body = readFileSync(rel, 'utf8'); } catch { continue; }
    const lines = body.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      const m = LOCAL_TREE_RE.exec(lines[i]);
      if (!m) continue;
      fail('R13', rel, i + 1,
        `cites the local-only tree \`${m[0]}\` - it is never committed, so the reference is dead for every reader`);
      break;
    }
  }
}

// ─── R14: No tracked generated or machine-local path ──────────────────────
// A .pyc, a build output or a SQLite file in the index is either a mistake or a leak. Gitignored
// copies never reach here, so a hit means the ignore rule has a hole.
const GENERATED_RE = [
  /(?:^|\/)__pycache__\//,
  /\.pyc$/,
  /(?:^|\/)node_modules\//,
  /(?:^|\/)\.next\//,
  /(?:^|\/)dist(?:-firefox)?\//,
  /(?:^|\/)coverage\//,
  /(?:^|\/)android\/build\//,
  /\.(?:db|db-wal|db-shm)$/,
];

function checkGeneratedPaths() {
  if (!COMMITTABLE) return;
  for (const rel of [...COMMITTABLE].sort()) {
    const hit = GENERATED_RE.find(re => re.test(rel));
    if (hit) fail('R14', rel, null, 'tracked generated or machine-local path - .gitignore has a hole');
  }
}

// ─── R15: No mojibake in a tracked text file ──────────────────────────────
// A UTF-8 file read as cp1252 and written back turns an em dash into three junk glyphs and a
// section sign into two. The repaired text is always correct UTF-8; a round trip through another
// codec is not the fix, and `chcp 65001` is not a repair either.
//
// Named separately from R13 so a mojibake hit is never mistaken for a tree citation.
//
// PowerShell note: a correct UTF-8 file renders as garbage in a cp437 console. Diagnose this with
// the checker, never by eye - `Get-Content` lies about the same bytes that Node reads correctly.
const MOJIBAKE_RE = /(?:\u00e2\u20ac|\u00c2\u00a7|\u00c2\u00ab|\u00c2\u00bb|\u00c2\u00bd|\u00c2\u00bc|\u00c2\u00a1|\u00c2\u00bf|\u00c3\u00a9|\u00c3\u00a8|\u00c3\u00a2|\u00c3\u00a4|\u00c3\u00b6|\u00c3\u00bc|\u0393\u00c7|\u252c\u00ba|\u252c\u00bd)/;


function checkMojibake() {
  if (!COMMITTABLE) return;
  for (const rel of [...COMMITTABLE].sort()) {
    if (!R13_EXTS.has(extname(rel))) continue;
    let body;
    try { body = readFileSync(rel, 'utf8'); } catch { continue; }
    const lines = body.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      if (!MOJIBAKE_RE.test(lines[i])) continue;
      // An applied migration cannot be edited (a content change is invisible to
      // `db push --dry-run`, so only a replay would ever notice), so its mojibake is reported and
      // lived with rather than failed. Anything else is a one-line fix in a tracked file.
      if (rel.startsWith('supabase/migrations/')) {
        warn('R15', rel, i + 1, 'mojibake in an applied migration - cannot be fixed in place; note it in the next migration');
      } else {
        fail('R15', rel, i + 1, 'mojibake - UTF-8 was read as cp1252 and written back; rewrite the text as UTF-8');
      }
      break;
    }
  }
}

// ─── R16: Every tracked doc under docs/ is linked from docs/INDEX.md ──────
// docs/DOCS.md has said "every doc in docs/ should be linked from here" since it was written; this
// is the first time anything checked that. An unlinked doc is a doc nobody finds.
function checkDocsIndex() {
  const index = 'docs/INDEX.md';
  if (!COMMITTABLE || !existsSync(index)) return;
  const body = readFileSync(index, 'utf8');
  const docs = [...COMMITTABLE].filter(p => /^docs\/[^/]+\.md$/.test(p) && p !== index).sort();
  for (const rel of docs) {
    if (!body.includes(basename(rel))) {
      fail('R16', rel, null, `not linked from ${index} - a doc nobody finds`);
    }
  }
}

// ─── R17 (warning): A commit that changes a manifest carries a `Deps:` trailer ─
// A dependency change and its reason travel together or the next reader cannot tell why a pin
// moved. Warning, not a failure: it is the only rule here that judges intent.
const MANIFESTS = new Set([
  'package.json', 'web/package.json', 'extension/package.json',
  'pnpm-lock.yaml', 'web/pnpm-lock.yaml', 'extension/pnpm-lock.yaml',
  'package-lock.json', 'web/package-lock.json',
  'deno.json', 'deno.lock', 'android/app/build.gradle.kts',
]);

function checkDepsTrailer() {
  let shas;
  try {
    shas = execSync('git rev-list origin/main..HEAD', { encoding: 'utf8' }).trim().split(/\r?\n/).filter(Boolean);
  } catch { return; }
  for (const sha of shas) {
    let files, body;
    try {
      files = execSync(`git show --name-only --format= ${sha}`, { encoding: 'utf8' }).split(/\r?\n/).filter(Boolean);
      body = execSync(`git log -1 --format=%B ${sha}`, { encoding: 'utf8' });
    } catch { continue; }
    if (!files.some(f => MANIFESTS.has(f.replace(/\\/g, '/')))) continue;
    if (/^Deps:\s*\S/m.test(body)) continue;
    warn('R17', sha.slice(0, 7), null, 'changes a manifest without a `Deps: <reason>` trailer');
  }
}

// ─── R18 (warning): Every tracked doc under docs/ carries a `Status:` line ─
// docs/DOCS.md's convention is `**Last Updated:**`, which says when a doc moved but not whether it
// still applies. `Status:` says the second thing, and the plan gate reads it too (W15).
function checkDocStatus() {
  if (!COMMITTABLE) return;
  for (const rel of [...COMMITTABLE].sort()) {
    if (!/^docs\/[^/]+\.md$/.test(rel)) continue;
    let body;
    try { body = readFileSync(rel, 'utf8'); } catch { continue; }
    if (!/^\*{0,2}Status\*{0,2}:/m.test(body.split('\n## ')[0])) {
      warn('R18', rel, null, 'no `Status:` line under the title - add one of current, draft, superseded, reference');
    }
  }
}

