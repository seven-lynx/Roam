package app.roam.android.util

import android.content.Context
import android.media.AudioManager
import android.media.SoundPool
import app.roam.android.R

/**
 * Low-latency sound-effect player built on [SoundPool].
 *
 * Gates every play call (in order): app foreground, per-category switch, device
 * ringer mode, then volume. The in-app master "Sound effects" toggle is still
 * enforced by callers (MainViewModel / loading screens) before calling [play].
 *
 * Volume and per-category switches are persisted by MainViewModel and pushed in
 * via [setVolume] / [setCategoryEnabled].
 *
 * The WAV assets in `res/raw/` are short, royalty-free clips generated by
 * `scripts/generate-sfx.mjs` (original synthesized tones — no attribution required).
 */
object SoundManager {
    /** Logical groups exposed in the Sound settings screen. */
    enum class Category { DECK, RATING, LOADING, CELEBRATION, ACTION }

    private var soundPool: SoundPool? = null
    private val soundIds = mutableMapOf<Int, Int>()
    private val categoryOf = mutableMapOf<Int, Category>()

    @Volatile private var foreground = true
    @Volatile private var volumeLevel = 1f
    val volume: Float get() = volumeLevel
    @Volatile var enabledCategories: Set<Category> = Category.entries.toSet()

    /** Called from ActivityLifecycleCallbacks so sounds never leak over other apps. */
    fun setForeground(fg: Boolean) { foreground = fg }

    fun setVolume(v: Float) { volumeLevel = v.coerceIn(0f, 1f) }

    fun setCategoryEnabled(category: Category, enabled: Boolean) {
        enabledCategories = if (enabled) enabledCategories + category else enabledCategories - category
    }

    fun isCategoryEnabled(category: Category) = category in enabledCategories

    /** Loads all SFX once. Safe to call repeatedly — subsequent calls are no-ops. */
    fun init(context: Context) {
        if (soundPool != null) return
        val appContext = context.applicationContext
        val attributes = android.media.AudioAttributes.Builder()
            .setUsage(android.media.AudioAttributes.USAGE_ASSISTANCE_SONIFICATION)
            .setContentType(android.media.AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build()
        soundPool = SoundPool.Builder()
            .setMaxStreams(4)
            .setAudioAttributes(attributes)
            .build()
            .also { pool ->
                listOf(
                    R.raw.badge_earn,
                    R.raw.level_up,
                    R.raw.challenge_complete,
                    R.raw.generic_success,
                    R.raw.click,
                    R.raw.click_heavy,
                    R.raw.load_start,
                    R.raw.load_complete,
                    R.raw.save_url,
                    R.raw.scan_blip,
                    R.raw.mount_complete,
                    R.raw.like,
                    R.raw.skip,
                    R.raw.server_hum,
                    R.raw.relay_tick,
                    R.raw.modem_blip,
                ).forEach { resId ->
                    soundIds[resId] = pool.load(appContext, resId, 1)
                    categoryOf[resId] = categoryFor(resId)
                }
            }
    }

    private fun categoryFor(resId: Int): Category = when (resId) {
        R.raw.click, R.raw.click_heavy -> Category.DECK
        R.raw.like, R.raw.skip -> Category.RATING
        R.raw.load_start, R.raw.load_complete, R.raw.scan_blip, R.raw.mount_complete,
        R.raw.server_hum, R.raw.relay_tick, R.raw.modem_blip -> Category.LOADING
        R.raw.badge_earn, R.raw.level_up, R.raw.challenge_complete, R.raw.generic_success -> Category.CELEBRATION
        R.raw.save_url -> Category.ACTION
        else -> Category.LOADING
    }

    /** Plays [resId] if allowed by every gate. */
    fun play(context: Context, resId: Int) {
        if (!foreground) return
        val cat = categoryOf[resId] ?: return
        if (cat !in enabledCategories) return
        val audioManager = context.getSystemService(Context.AUDIO_SERVICE) as? AudioManager ?: return
        val ringerMode = audioManager.ringerMode
        if (ringerMode == AudioManager.RINGER_MODE_SILENT || ringerMode == AudioManager.RINGER_MODE_VIBRATE) {
            return
        }
        if (volume <= 0f) return
        val pool = soundPool ?: return
        val id = soundIds[resId] ?: return
        pool.play(id, volume, volume, 1, 0, 1f)
    }
}
