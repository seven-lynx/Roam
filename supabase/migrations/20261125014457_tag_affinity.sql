-- =============================================================================
-- Roam - subcategory -> tag affinity (the onboarding prior's source)
-- =============================================================================
-- Issue #147: `subcategory_tag_mapping` is a hand-written bridge and agrees with
-- the tagger's tags on only 21.88 % of tagged URLs, so a prior built from it would
-- seed a brand-new user with tags the corpus barely carries (`modern-history`
-- has 15,783 tagged URLs and 3 agree).
--
-- This table holds the corpus-derived alternative: for each subcategory, the
-- share of its tagged URLs that carry each tag. Measured 2026-11-24 over
-- 782,357 tagged URLs: 61 subcategories, 667 rows, mean 10.9 tags each.
--
-- The rows are GENERATED by scripts/tag-graph-derive.mjs into the sibling
-- `<version>_seed_tag_affinity.sql`; this file is the shape, that one is data.
-- Read by `user_tag_prior(uuid)` (tag-rollout segment T10).
--
-- Rollback: DROP TABLE public.subcategory_tag_affinity;  (see RUNBOOK.md)
-- =============================================================================

CREATE TABLE public.subcategory_tag_affinity (
  subcategory_slug TEXT         NOT NULL REFERENCES public.subcategories(slug) ON DELETE CASCADE,
  tag_id           UUID         NOT NULL REFERENCES public.tags(id) ON DELETE CASCADE,
  -- Both counts are stored, not just the ratio, so a reader can see how much
  -- evidence a row carries without re-joining the corpus.
  url_count        INTEGER      NOT NULL CHECK (url_count >= 0),
  tag_count        INTEGER      NOT NULL CHECK (tag_count >= 0),
  weight           NUMERIC(5,4) NOT NULL CHECK (weight >= 0 AND weight <= 1),
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  PRIMARY KEY (subcategory_slug, tag_id),
  CHECK (tag_count <= url_count)
);

-- The prior reads "these tags, for these subcategories"; the reverse lookup is
-- for tuning ("which subcategories lean on tag X").
CREATE INDEX idx_subcategory_tag_affinity_tag ON public.subcategory_tag_affinity(tag_id);
CREATE INDEX idx_subcategory_tag_affinity_weight ON public.subcategory_tag_affinity(weight DESC);

ALTER TABLE public.subcategory_tag_affinity ENABLE ROW LEVEL SECURITY;

-- Taxonomy data: public read, admin write - the same posture as `tags`,
-- `tag_relations` and `subcategory_tag_mapping`.
CREATE POLICY "subcategory_tag_affinity: readable by everyone"
  ON public.subcategory_tag_affinity FOR SELECT USING (TRUE);
CREATE POLICY "subcategory_tag_affinity: admin write"
  ON public.subcategory_tag_affinity FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

